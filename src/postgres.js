'use strict';
const {Worker,MessageChannel,receiveMessageOnPort}=require('node:worker_threads');
const path=require('node:path'),crypto=require('node:crypto');
const IDENTITIES=new Set(['groups','ledgers','vouchers','entries','items','stock_moves','order_lines','pricebooks','cheques','custom_fields','catalog_masters']);

// Translate the engine's small SQL dialect; values always remain bound parameters.
function sqlForPostgres(source){
  let sql=source.replace(/--[^\n]*/g,'')
    .replace(/\bBEGIN IMMEDIATE\b/gi,'BEGIN')
    .replace(/\bid INTEGER PRIMARY KEY\b/g,'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/TEXT NOT NULL UNIQUE COLLATE NOCASE/g,'CITEXT NOT NULL UNIQUE')
    .replace(/\bINTEGER\b/g,'BIGINT').replace(/\bBLOB\b/g,'BYTEA')
    .replace(/json_extract\((\w+(?:\.\w+)?),'\$\.(\w+)'\)/g,"($1::jsonb->>'$2')")
    .replace(/(\w+(?:\.\w+)?)\s+COLLATE NOCASE/gi,'lower($1)')
    .replace(/label=\? COLLATE NOCASE/gi,'lower(label)=lower(?)')
    .replace(/(\([^)]*::jsonb[^)]*\))=\? COLLATE NOCASE/g,'lower($1)=lower(?)')
    .replace(/\bIS NOT \?/g,'IS DISTINCT FROM ?')
    .replace(/\bAS ([a-z]\w*[A-Z]\w*)/g,'AS "$1"');
  // Match literals separately so question marks in text are never parameters.
  let next=0;
  sql=sql.replace(/'(?:''|[^'])*'|\?(\d+)?/g,(token,index)=>{
    if(token.startsWith("'"))return token;
    const at=index?Number(index):next+1;next=Math.max(next,at);return `$${at}`;
  }).replace(/(\$\d+) IS NULL/g,'$1::text IS NULL');
  if(/INSERT OR REPLACE INTO cleared/i.test(sql))sql=sql.replace(/INSERT OR REPLACE/i,'INSERT')+' ON CONFLICT (voucher_id,ledger_id) DO UPDATE SET date=excluded.date';
  return sql;
}

class PostgresDatabase {
  constructor(file,config={connectionString:process.env.DESKTOP_ERP_PG_URL}){
    if(!config.connectionString&&!config.host)throw Error('PostgreSQL has not been started');
    const {port1,port2}=new MessageChannel();this.port=port1;this.signal=new SharedArrayBuffer(4);this.flag=new Int32Array(this.signal);
    this.worker=new Worker(path.join(__dirname,'postgres-worker.js'),{workerData:{port:port2,signal:this.signal,config},transferList:[port2]});
    this.worker.on('error',()=>{});this.worker.unref();this.port.unref();
    this.schema='books_'+(file===':memory:'?crypto.randomUUID().replaceAll('-',''):crypto.createHash('sha256').update(path.resolve(file).toLowerCase()).digest('hex').slice(0,24));
    try{
      this.query(`CREATE SCHEMA IF NOT EXISTS "${this.schema}"`);
      this.query('SELECT pg_advisory_lock(1397772101,1)');
      try{this.query('CREATE EXTENSION IF NOT EXISTS citext WITH SCHEMA public');}finally{this.query('SELECT pg_advisory_unlock(1397772101,1)');}
      this.query(`SET search_path TO "${this.schema}", public`);
      // One owner per books dataset avoids voucher-number and stock races.
      if(!this.query('SELECT pg_try_advisory_lock(hashtext($1)) AS locked',[this.schema]).rows[0].locked)throw Error('These books are already open in another application');
      this.query('CREATE TABLE IF NOT EXISTS _schema(version INTEGER NOT NULL)');
      this.query('INSERT INTO _schema SELECT 0 WHERE NOT EXISTS (SELECT 1 FROM _schema)');
      this.dialect='postgres';
    }catch(error){this.worker.terminate();throw error;}
  }
  query(sql,values,close=false){
    if(this.closed)throw Error('Database connection is closed');
    Atomics.store(this.flag,0,0);this.port.postMessage({sql,values,close});
    if(Atomics.wait(this.flag,0,0,45000)==='timed-out'){this.closed=true;this.worker.terminate();throw Error('PostgreSQL did not respond. Restart the app before continuing.');}
    const message=receiveMessageOnPort(this.port)?.message;
    if(!message?.ok){const error=new Error(message?.error?.message||'PostgreSQL worker failed');error.code=message?.error?.code;throw error;}
    return message;
  }
  exec(source){
    for(const part of source.replace(/--[^\n]*/g,'').split(';').map(s=>s.trim()).filter(Boolean)){
      if(/^PRAGMA (journal_mode|foreign_keys)/i.test(part))continue;
      const version=part.match(/^PRAGMA user_version\s*=\s*(\d+)$/i);
      if(version){this.query('UPDATE _schema SET version=$1',[Number(version[1])]);continue;}
      this.query(sqlForPostgres(part));
    }
  }
  prepare(source){
    const version=/^PRAGMA user_version$/i.test(source.trim());
    let sql=version?'SELECT version AS user_version FROM _schema':sqlForPostgres(source);
    const table=source.match(/^\s*INSERT INTO (\w+)/i)?.[1];
    const runSql=IDENTITIES.has(table)&&! /\bRETURNING\b/i.test(sql)?sql+' RETURNING id':sql;
    return {
      all:(...values)=>this.query(sql,values).rows,
      get:(...values)=>this.query(sql,values).rows[0],
      run:(...values)=>{const r=this.query(runSql,values);return {changes:r.changes,lastInsertRowid:r.rows[0]?.id};},
    };
  }
  close(){if(this.closed)return;try{this.query('',undefined,true);}finally{this.closed=true;this.worker.terminate();this.port.close();}}
}
module.exports={PostgresDatabase,sqlForPostgres};
